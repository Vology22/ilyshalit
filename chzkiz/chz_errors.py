UNKNOWN = "Пришлите скрин в поддержку: в боте Помощь, Написать в поддержку."


def _has_marker(raw: str, low: str, marker: str) -> bool:
    # латинский маркер: слева граница слова или заглавная буква после строчной (documentDate),
    # справа граница не нужна (fiasId); date не срабатывает на validate и update
    if marker.isascii() and marker == marker.strip():
        for m in re.finditer(re.escape(marker), raw, re.IGNORECASE | re.ASCII):
            i = m.start()
            prev = raw[i - 1] if i else ""
            if not prev.isalnum() or (raw[i].isupper() and not prev.isupper()):
                return True
        return False
    return marker in low


def explain(text: str | None) -> str:
    raw = (text or "").strip()
    if not raw:
        return ""
    low = f" {raw.lower().replace(chr(1105), chr(1077))} "
    for keys, answer in _RULES:
        if any(_has_marker(raw, low, k) for k in keys):
            return answer
    return f"{raw}. {UNKNOWN}"
